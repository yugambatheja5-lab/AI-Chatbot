
import { useEffect, useState } from "react";
import { Settings, Sparkles } from "lucide-react";
import Sidebar from "./components/Sidebar";
import ChatWindow from "./components/ChatWindow";
import { useChat } from "./hooks/useChat";
import { useTheme } from "./hooks/useTheme";

export default function App() {
  const [sidebarOpen, setSidebarOpen] = useState(false);
  const [sidebarCollapsed, setSidebarCollapsed] = useState(false);
  const [settingsOpen, setSettingsOpen] = useState(false);
  const { theme, toggleTheme } = useTheme();
  const {
    conversations,
    activeConversation,
    activeId,
    isGenerating,
    newChat,
    selectConversation,
    renameConversation,
    deleteConversation,
    pinConversation,
    send,
    stop,
    regenerate,
    setFeedback,
  } = useChat();

  useEffect(() => {
  const open = () => {
    setSidebarOpen(true);
    setSidebarCollapsed(false);
  };

  const expandSidebar = () => {
    setSidebarCollapsed(false);
  };

  window.addEventListener(
    "knowledge-ai:open-sidebar",
    open
  );

  window.addEventListener(
    "knowledge-ai:expand-sidebar",
    expandSidebar
  );

  const keyboard = (event) => {
    if (
      (event.ctrlKey || event.metaKey) &&
      event.key.toLowerCase() === "k"
    ) {
      event.preventDefault();
      newChat();
    }

    if (event.key === "Escape") {
      setSidebarOpen(false);
      setSettingsOpen(false);
    }
  };

  window.addEventListener("keydown", keyboard);

  return () => {
    window.removeEventListener(
      "knowledge-ai:open-sidebar",
      open
    );

    window.removeEventListener(
      "knowledge-ai:expand-sidebar",
      expandSidebar
    );

    window.removeEventListener(
      "keydown",
      keyboard
    );
  };
}, [newChat]);

  return (
    <div className="app-shell">
      <Sidebar
        open={sidebarOpen}
        onClose={() => setSidebarOpen(false)}
        onPin={pinConversation}
        conversations={conversations}
        activeId={activeId}
        onNewChat={() => { newChat(); setSidebarOpen(false); }}
        onSelect={(id) => { selectConversation(id); setSidebarOpen(false); }}
        onRename={renameConversation}
        onDelete={deleteConversation}
        theme={theme}
        onToggleTheme={toggleTheme}
        collapsed={sidebarCollapsed}
        onToggleCollapse={() => setSidebarCollapsed((v) => !v)}
        onSettings={() => setSettingsOpen(true)}
      />

      <ChatWindow
        conversation={activeConversation}
        isGenerating={isGenerating}
        onNewChat={newChat}
        onSend={send}
        onStop={stop}
        onRegenerate={regenerate}
        onFeedback={setFeedback}
      />

      {settingsOpen && (
        <div className="modal-backdrop" onMouseDown={() => setSettingsOpen(false)}>
          <div
            className="settings-modal"
            onMouseDown={(e) => e.stopPropagation()}
          >
            <div className="flex items-start gap-3">
              <div className="icon-tile"><Settings size={19} /></div>
              <div className="min-w-0 flex-1">
                <h2 className="text-base font-semibold">Settings</h2>
                <p className="mt-1 text-sm text-zinc-500 dark:text-zinc-400">
                  Local preferences for this demo workspace.
                </p>
              </div>
              <button className="icon-button" onClick={() => setSettingsOpen(false)} aria-label="Close settings">×</button>
            </div>

            <div className="mt-6 space-y-3">
              <div className="setting-row">
                <div>
                  <p className="font-medium">Appearance</p>
                  <p className="text-xs text-zinc-500">Currently using {theme} mode.</p>
                </div>
                <button className="secondary-button" onClick={toggleTheme}>
                  {theme === "dark" ? "Light mode" : "Dark mode"}
                </button>
              </div>
              <div className="setting-row">
                <div>
                  <p className="font-medium">Model</p>
                  <p className="text-xs text-zinc-500">Running locally with Ollama and the RAG backend.</p>
                </div>
                <span className="badge"><Sparkles size={13} /> Qwen 3 4B</span>
              </div>
              <div className="rounded-xl border border-zinc-200 bg-zinc-50 p-3 text-xs leading-5 text-zinc-500 dark:border-zinc-800 dark:bg-zinc-900/60 dark:text-zinc-400">
                Conversations are stored locally in your browser. Responses are generated by your local FastAPI + Ollama RAG backend.
              </div>
            </div>

            <button className="primary-button mt-6 w-full" onClick={() => setSettingsOpen(false)}>
              Done
            </button>
          </div>
        </div>
      )}
    </div>
  );
}
